-- Quỹ dư của đội: tiền thừa do làm tròn khi chia tiền, dùng cho trận sau
ALTER TABLE team ADD COLUMN fund_balance NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE team ADD CONSTRAINT ck_team_fund CHECK (fund_balance >= 0);

-- Nhật ký quỹ — chỉ ghi thêm
CREATE TABLE team_fund_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id       BIGINT        NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    delta         NUMERIC(12,2) NOT NULL,
    reason        VARCHAR(200)  NOT NULL,
    split_bill_id BIGINT,
    balance_after NUMERIC(12,2) NOT NULL,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_team_fund_log ON team_fund_log (team_id, created_at DESC);

-- Mỗi trận một bảng chia tiền
CREATE TABLE split_bill (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      BIGINT        NOT NULL UNIQUE REFERENCES booking(id) ON DELETE CASCADE,
    team_id         BIGINT        REFERENCES team(id),
    captain_id      BIGINT        NOT NULL REFERENCES app_user(id),
    -- EQUAL: chia đều; SPONSOR: đội trưởng tài trợ %, chia đều phần còn lại; CUSTOM: nhập từng người
    mode            VARCHAR(10)   NOT NULL,
    sponsor_percent SMALLINT      NOT NULL DEFAULT 0,
    total_amount    NUMERIC(12,2) NOT NULL,    -- tiền sân + dịch vụ
    sponsor_amount  NUMERIC(12,2) NOT NULL DEFAULT 0,
    surplus         NUMERIC(12,2) NOT NULL DEFAULT 0,  -- tiền thừa do làm tròn -> quỹ đội
    -- Tài khoản nhận tiền của đội trưởng
    bank_name       VARCHAR(50)   NOT NULL,
    bank_account    VARCHAR(30)   NOT NULL,
    bank_holder     VARCHAR(120)  NOT NULL,
    due_at          TIMESTAMPTZ   NOT NULL,    -- hạn đóng, quá hạn thì nhắc
    status          VARCHAR(10)   NOT NULL DEFAULT 'OPEN',
    completed_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_split_mode CHECK (mode IN ('EQUAL', 'SPONSOR', 'CUSTOM')),
    CONSTRAINT ck_split_status CHECK (status IN ('OPEN', 'DONE')),
    CONSTRAINT ck_split_sponsor CHECK (sponsor_percent BETWEEN 0 AND 100),
    CONSTRAINT ck_split_amounts CHECK (total_amount > 0 AND surplus >= 0 AND sponsor_amount >= 0)
);

-- Phần phải đóng của từng người. Đội phủi có người không có tài khoản -> user_id có thể NULL, định danh bằng SĐT
CREATE TABLE split_bill_share (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    split_bill_id BIGINT        NOT NULL REFERENCES split_bill(id) ON DELETE CASCADE,
    user_id       BIGINT        REFERENCES app_user(id),
    name          VARCHAR(120)  NOT NULL,
    phone         VARCHAR(10)   NOT NULL,
    amount        NUMERIC(12,2) NOT NULL,
    -- UNPAID | PAID (chuyển khoản / đội trưởng xác nhận) | PAID_BY_CAPTAIN (đóng thay) | REASSIGNED (đã đổi người)
    status        VARCHAR(20)   NOT NULL DEFAULT 'UNPAID',
    paid_at       TIMESTAMPTZ,
    reminded_at   TIMESTAMPTZ,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_share_status CHECK (status IN ('UNPAID', 'PAID', 'PAID_BY_CAPTAIN', 'REASSIGNED')),
    CONSTRAINT ck_share_amount CHECK (amount >= 0),
    CONSTRAINT ck_share_phone CHECK (phone ~ '^0[0-9]{9}$')
);
-- Một SĐT chỉ có một phần đang hiệu lực trong một bảng chia
CREATE UNIQUE INDEX uq_share_phone ON split_bill_share (split_bill_id, phone) WHERE status <> 'REASSIGNED';
CREATE INDEX ix_share_user ON split_bill_share (user_id) WHERE user_id IS NOT NULL;

-- Giao dịch ngân hàng có thể khớp vào một phần chia tiền thay vì một đơn
ALTER TABLE bank_transaction ADD COLUMN split_share_id BIGINT REFERENCES split_bill_share(id) ON DELETE SET NULL;
ALTER TABLE bank_transaction DROP CONSTRAINT ck_bank_txn_booking;
ALTER TABLE bank_transaction ADD CONSTRAINT ck_bank_txn_target
    CHECK (status NOT IN ('PARTIAL', 'APPLIED') OR booking_id IS NOT NULL OR split_share_id IS NOT NULL);

