CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- unaccent() chỉ là STABLE nên không dùng được trong cột GENERATED / index;
-- bọc lại với từ điển cố định để khai báo IMMUTABLE
CREATE OR REPLACE FUNCTION f_unaccent(text) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $$ SELECT public.unaccent('public.unaccent'::regdictionary, $1) $$;

CREATE TABLE kb_article (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(80)  NOT NULL,
    title       VARCHAR(200) NOT NULL,
    category    VARCHAR(30)  NOT NULL,
    -- Ai được đọc bài này: GUEST = chưa đăng nhập
    audience    TEXT[]       NOT NULL DEFAULT ARRAY['GUEST', 'PLAYER'],
    -- Trang web mà bài viết hướng dẫn (đường dẫn frontend), NULL nếu không gắn trang
    route       VARCHAR(200),
    -- Từ đồng nghĩa / cách hỏi khác để tìm kiếm từ vựng bắt trúng hơn
    keywords    TEXT         NOT NULL DEFAULT '',
    content     TEXT         NOT NULL,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    updated_by  BIGINT       REFERENCES app_user(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    search_vector TSVECTOR GENERATED ALWAYS AS (
        setweight(to_tsvector('simple', lower(f_unaccent(title))), 'A') ||
        setweight(to_tsvector('simple', lower(f_unaccent(keywords))), 'A') ||
        setweight(to_tsvector('simple', lower(f_unaccent(content))), 'B')
    ) STORED,
    CONSTRAINT uq_kb_article_slug UNIQUE (slug),
    CONSTRAINT ck_kb_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_kb_category CHECK (category IN ('BOOKING', 'PAYMENT', 'POLICY', 'COMMUNITY', 'ACCOUNT', 'OWNER', 'ADMIN', 'GENERAL')),
    CONSTRAINT ck_kb_audience CHECK (
        cardinality(audience) > 0 AND audience <@ ARRAY['GUEST', 'PLAYER', 'OWNER', 'ADMIN']
    ),
    CONSTRAINT ck_kb_route CHECK (route IS NULL OR route ~ '^/'),
    CONSTRAINT ck_kb_content_len CHECK (char_length(content) BETWEEN 20 AND 4000)
);

CREATE INDEX idx_kb_article_search ON kb_article USING GIN (search_vector);
CREATE INDEX idx_kb_article_title_trgm ON kb_article USING GIN (lower(f_unaccent(title || ' ' || keywords)) gin_trgm_ops);
CREATE INDEX idx_kb_article_audience ON kb_article USING GIN (audience);
