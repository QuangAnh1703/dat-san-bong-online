-- Giá trị enum mới không dùng trong cùng file migration (PostgreSQL cấm dùng trước khi COMMIT)
ALTER TYPE payment_method ADD VALUE IF NOT EXISTS 'WALLET';

CREATE TABLE membership_plan (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id         BIGINT        NOT NULL REFERENCES venue(id) ON DELETE CASCADE,
    name             VARCHAR(60)   NOT NULL,
    price            NUMERIC(12,2) NOT NULL,            -- số tiền nạp
    bonus            NUMERIC(12,2) NOT NULL DEFAULT 0,  -- tiền tặng thêm vào ví
    discount_percent SMALLINT      NOT NULL DEFAULT 0,  -- giảm thêm tiền sân khi trả bằng ví
    is_active        BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_plan_price CHECK (price > 0 AND bonus >= 0),
    CONSTRAINT ck_plan_discount CHECK (discount_percent BETWEEN 0 AND 50),
    CONSTRAINT uq_plan_name UNIQUE (venue_id, name)
);

-- Một người một ví cho mỗi cụm sân
CREATE TABLE member_wallet (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    venue_id   BIGINT        NOT NULL REFERENCES venue(id) ON DELETE CASCADE,
    plan_id    BIGINT        REFERENCES membership_plan(id),
    balance    NUMERIC(12,2) NOT NULL DEFAULT 0,
    -- FROZEN: cụm sân bị khóa / ngừng kinh doanh, chờ admin hoàn tiền
    status     VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_wallet UNIQUE (user_id, venue_id),
    CONSTRAINT ck_wallet_balance CHECK (balance >= 0),
    CONSTRAINT ck_wallet_status CHECK (status IN ('ACTIVE', 'FROZEN'))
);
CREATE INDEX ix_wallet_venue ON member_wallet (venue_id, status);

-- Nhật ký ví — chỉ ghi thêm. amount có dấu: + nạp/tặng/hoàn, - trả tiền / admin hoàn ra ngoài
CREATE TABLE wallet_txn (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id     BIGINT        NOT NULL REFERENCES member_wallet(id) ON DELETE CASCADE,
    type          VARCHAR(15)   NOT NULL,
    amount        NUMERIC(12,2) NOT NULL,
    balance_after NUMERIC(12,2) NOT NULL,
    booking_id    BIGINT        REFERENCES booking(id) ON DELETE SET NULL,
    note          VARCHAR(200),
    created_by    BIGINT        REFERENCES app_user(id),
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_wallet_txn_type CHECK (type IN ('TOPUP', 'BONUS', 'PAY', 'REFUND', 'ADMIN_REFUND'))
);
CREATE INDEX ix_wallet_txn ON wallet_txn (wallet_id, created_at DESC);

-- Lệnh mua gói chờ chuyển khoản, nội dung CK: NAP <code>
CREATE TABLE wallet_topup (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(20)   NOT NULL UNIQUE,
    user_id    BIGINT        NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    venue_id   BIGINT        NOT NULL REFERENCES venue(id) ON DELETE CASCADE,
    plan_id    BIGINT        NOT NULL REFERENCES membership_plan(id),
    amount     NUMERIC(12,2) NOT NULL,
    status     VARCHAR(10)   NOT NULL DEFAULT 'PENDING',
    paid_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_topup_status CHECK (status IN ('PENDING', 'PAID', 'CANCELLED'))
);

ALTER TABLE bank_transaction ADD COLUMN topup_id BIGINT REFERENCES wallet_topup(id) ON DELETE SET NULL;
ALTER TABLE bank_transaction DROP CONSTRAINT ck_bank_txn_target;
ALTER TABLE bank_transaction ADD CONSTRAINT ck_bank_txn_target
    CHECK (status NOT IN ('PARTIAL', 'APPLIED') OR booking_id IS NOT NULL OR split_share_id IS NOT NULL
           OR topup_id IS NOT NULL);

