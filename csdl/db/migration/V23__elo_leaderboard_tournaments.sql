-- Kết quả trận cáp kèo giao hữu: mỗi đội trưởng tự nhập, khớp thì tính Elo
CREATE TABLE match_result (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id        BIGINT      NOT NULL UNIQUE REFERENCES booking(id) ON DELETE CASCADE,
    home_team_id      BIGINT      NOT NULL REFERENCES team(id),
    away_team_id      BIGINT      NOT NULL REFERENCES team(id),
    home_claim_home   SMALLINT,   -- tỷ số đội nhà nhập
    home_claim_away   SMALLINT,
    away_claim_home   SMALLINT,   -- tỷ số đội khách nhập
    away_claim_away   SMALLINT,
    -- PENDING: chờ đủ 2 bên; CONFIRMED: khớp, đã tính Elo; DISPUTED: lệch, chờ sửa 12h; VOID: quá hạn, không tính
    status            VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    dispute_due_at    TIMESTAMPTZ,
    home_elo_delta    INTEGER,
    away_elo_delta    INTEGER,
    confirmed_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_result_status CHECK (status IN ('PENDING', 'CONFIRMED', 'DISPUTED', 'VOID')),
    CONSTRAINT ck_result_teams CHECK (home_team_id <> away_team_id),
    CONSTRAINT ck_result_scores CHECK (
        COALESCE(home_claim_home, 0) BETWEEN 0 AND 99 AND COALESCE(home_claim_away, 0) BETWEEN 0 AND 99
        AND COALESCE(away_claim_home, 0) BETWEEN 0 AND 99 AND COALESCE(away_claim_away, 0) BETWEEN 0 AND 99)
);
CREATE INDEX ix_result_disputed ON match_result (dispute_due_at) WHERE status = 'DISPUTED';

CREATE TABLE tournament (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id              BIGINT        NOT NULL REFERENCES venue(id) ON DELETE CASCADE,
    field_id              BIGINT        NOT NULL REFERENCES field(id),
    organizer_id          BIGINT        NOT NULL REFERENCES app_user(id),
    name                  VARCHAR(120)  NOT NULL,
    description           VARCHAR(1000),
    format                VARCHAR(15)   NOT NULL,     -- ROUND_ROBIN | KNOCKOUT
    max_teams             SMALLINT      NOT NULL,
    fee                   NUMERIC(12,2) NOT NULL DEFAULT 0,
    registration_deadline TIMESTAMPTZ   NOT NULL,
    start_date            DATE          NOT NULL,
    daily_start_minute    SMALLINT      NOT NULL,     -- giờ bắt đầu xếp trận mỗi ngày (phút trong ngày)
    daily_end_minute      SMALLINT      NOT NULL,
    match_minutes         SMALLINT      NOT NULL DEFAULT 60,
    -- OPEN: nhận đăng ký; ONGOING: đã xếp lịch; FINISHED; CANCELLED
    status                VARCHAR(10)   NOT NULL DEFAULT 'OPEN',
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_tournament_format CHECK (format IN ('ROUND_ROBIN', 'KNOCKOUT')),
    CONSTRAINT ck_tournament_teams CHECK (max_teams BETWEEN 2 AND 32),
    CONSTRAINT ck_tournament_fee CHECK (fee >= 0),
    CONSTRAINT ck_tournament_window CHECK (daily_start_minute >= 0 AND daily_end_minute <= 1440
                                           AND daily_end_minute - daily_start_minute >= match_minutes),
    CONSTRAINT ck_tournament_match_minutes CHECK (match_minutes BETWEEN 60 AND 120),
    CONSTRAINT ck_tournament_status CHECK (status IN ('OPEN', 'ONGOING', 'FINISHED', 'CANCELLED'))
);
CREATE INDEX ix_tournament_status ON tournament (status, start_date);

CREATE TABLE tournament_team (
    tournament_id BIGINT        NOT NULL REFERENCES tournament(id) ON DELETE CASCADE,
    team_id       BIGINT        NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    fee_code      VARCHAR(20)   NOT NULL UNIQUE,      -- nội dung CK: GIAI <fee_code>
    -- PENDING_PAYMENT: chờ lệ phí; REGISTERED; WITHDRAWN: bỏ giải
    status        VARCHAR(20)   NOT NULL DEFAULT 'PENDING_PAYMENT',
    group_label   VARCHAR(5),
    paid_at       TIMESTAMPTZ,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    PRIMARY KEY (tournament_id, team_id),
    CONSTRAINT ck_tt_status CHECK (status IN ('PENDING_PAYMENT', 'REGISTERED', 'WITHDRAWN'))
);

CREATE TABLE tournament_match (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT      NOT NULL REFERENCES tournament(id) ON DELETE CASCADE,
    round         SMALLINT    NOT NULL,
    group_label   VARCHAR(5),
    home_team_id  BIGINT      REFERENCES team(id),
    away_team_id  BIGINT      REFERENCES team(id),   -- NULL = đội nhà được miễn đấu (loại trực tiếp lẻ đội)
    booking_id    BIGINT      REFERENCES booking(id) ON DELETE SET NULL,
    starts_at     TIMESTAMPTZ,
    home_score    SMALLINT,
    away_score    SMALLINT,
    -- SCHEDULED | PLAYED | FORFEIT (một đội bỏ trận, xử thua 0-3) | BYE
    status        VARCHAR(10) NOT NULL DEFAULT 'SCHEDULED',
    forfeit_team_id BIGINT    REFERENCES team(id),
    CONSTRAINT ck_tm_status CHECK (status IN ('SCHEDULED', 'PLAYED', 'FORFEIT', 'BYE'))
);
CREATE INDEX ix_tm_tournament ON tournament_match (tournament_id, round, starts_at);

