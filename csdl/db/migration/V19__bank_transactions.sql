-- Mỗi biến động số dư (tiền vào) ngân hàng / cổng trung gian báo về.
-- UNIQUE (provider, provider_txn_id) chống xử lý trùng khi webhook gọi lại.
-- Số tiền khách đã trả cho một đơn = tổng các dòng PARTIAL + APPLIED của đơn đó.
CREATE TABLE bank_transaction (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider        VARCHAR(20)   NOT NULL,          -- SEPAY | MOCK
    provider_txn_id VARCHAR(64)   NOT NULL,
    account_number  VARCHAR(30),                     -- tài khoản nhận tiền
    bank_name       VARCHAR(50),
    amount          NUMERIC(12,2) NOT NULL,
    content         VARCHAR(500)  NOT NULL DEFAULT '',
    reference_code  VARCHAR(64),
    transaction_at  TIMESTAMPTZ,

    booking_id      BIGINT        REFERENCES booking(id) ON DELETE SET NULL,
    -- PARTIAL        : đã khớp đơn, đơn còn chờ đủ tiền cọc
    -- APPLIED        : đã tính vào đơn đã xác nhận
    -- UNMATCHED      : không tự khớp được -> hàng đợi đối soát thủ công
    -- REFUND_PENDING : tiền về khi đơn đã hết hạn / bị hủy -> chờ hoàn
    -- REFUNDED / IGNORED : đã xử lý tay (hoàn lại / ghi nhận ngoài hệ thống)
    status          VARCHAR(20)   NOT NULL DEFAULT 'UNMATCHED',
    note            VARCHAR(300),
    handled_by      BIGINT        REFERENCES app_user(id),
    handled_at      TIMESTAMPTZ,
    raw_payload     JSONB         NOT NULL,
    received_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT uq_bank_txn UNIQUE (provider, provider_txn_id),
    CONSTRAINT ck_bank_txn_amount CHECK (amount > 0),
    CONSTRAINT ck_bank_txn_status CHECK (status IN ('PARTIAL', 'APPLIED', 'UNMATCHED', 'REFUND_PENDING', 'REFUNDED', 'IGNORED')),
    CONSTRAINT ck_bank_txn_booking CHECK (status NOT IN ('PARTIAL', 'APPLIED') OR booking_id IS NOT NULL)
);
CREATE INDEX ix_bank_txn_status  ON bank_transaction (status, received_at DESC);
CREATE INDEX ix_bank_txn_booking ON bank_transaction (booking_id) WHERE booking_id IS NOT NULL;
COMMENT ON TABLE bank_transaction IS 'Biến động số dư từ webhook ngân hàng, dùng để tự khớp tiền cọc';

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sanbong') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON bank_transaction TO sanbong;
        GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO sanbong;
    END IF;
END $$;
