-- V11 — Owner Request Management (Yêu cầu nâng cấp lên chủ sân)
-- =====================================================================

-- Bảng quản lý yêu cầu nâng cấp từ PLAYER → OWNER
CREATE TABLE owner_request (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    status          VARCHAR(20) NOT NULL DEFAULT 'PENDING',  -- PENDING | APPROVED | REJECTED
    requested_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at     TIMESTAMPTZ,
    reviewed_by     BIGINT      REFERENCES app_user(id) ON DELETE SET NULL,
    rejection_reason VARCHAR(500),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_owner_request_user_pending ON owner_request (user_id)
WHERE status = 'PENDING';
CREATE INDEX ix_owner_request_status ON owner_request (status, requested_at DESC);
CREATE INDEX ix_owner_request_reviewed_by ON owner_request (reviewed_by);

COMMENT ON TABLE owner_request IS 'Quản lý yêu cầu nâng cấp vai trò PLAYER → OWNER (phải được admin duyệt)';
