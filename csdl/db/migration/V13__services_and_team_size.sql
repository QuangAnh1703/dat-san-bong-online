-- Dịch vụ chủ sân bán kèm (nước, áo bib, bóng, trọng tài...)
CREATE TABLE venue_service (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id   BIGINT        NOT NULL REFERENCES venue(id) ON DELETE CASCADE,
    name       VARCHAR(120)  NOT NULL,
    price      NUMERIC(12,2) NOT NULL,
    is_active  BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_service_price CHECK (price >= 0),
    CONSTRAINT uq_service_name UNIQUE (venue_id, name)
);
CREATE INDEX ix_venue_service ON venue_service (venue_id) WHERE is_active;

-- Dịch vụ đã chọn trong một đơn; lưu lại giá tại thời điểm đặt
CREATE TABLE booking_service (
    booking_id BIGINT        NOT NULL REFERENCES booking(id) ON DELETE CASCADE,
    service_id BIGINT        NOT NULL REFERENCES venue_service(id),
    name       VARCHAR(120)  NOT NULL,
    price      NUMERIC(12,2) NOT NULL,
    PRIMARY KEY (booking_id, service_id)
);

-- Số thành viên do đội trưởng khai báo (đội phủi thường không có tài khoản cho từng người)
ALTER TABLE team ADD COLUMN member_count SMALLINT NOT NULL DEFAULT 10;
ALTER TABLE team ADD CONSTRAINT ck_team_member_count CHECK (member_count BETWEEN 1 AND 50);

-- Mỗi người chỉ làm đội trưởng một đội (màn hình hồ sơ quản lý đúng một đội)
CREATE UNIQUE INDEX uq_team_captain ON team (captain_id);

-- Dịch vụ mặc định cho các cụm sân đã có
INSERT INTO venue_service (venue_id, name, price)
SELECT v.id, s.name, s.price
  FROM venue v
 CROSS JOIN (VALUES
       ('2 thùng nước suối ướp lạnh', 60000),
       ('Thuê 2 bộ áo bib', 40000),
       ('Bóng thi đấu tiêu chuẩn', 30000),
       ('Thuê trọng tài', 200000)) AS s(name, price)
ON CONFLICT DO NOTHING;

-- Bảng mới do user chạy migration sở hữu -> cấp quyền cho user của ứng dụng (nếu có)
