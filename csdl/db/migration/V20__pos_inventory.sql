-- Danh mục + tồn kho. stock NULL = không quản kho (VD: thuê trọng tài)
ALTER TABLE venue_service ADD COLUMN category VARCHAR(20) NOT NULL DEFAULT 'OTHER';
ALTER TABLE venue_service ADD COLUMN stock INTEGER;
ALTER TABLE venue_service ADD CONSTRAINT ck_service_category
    CHECK (category IN ('DRINK', 'RENTAL', 'BALL', 'REFEREE', 'OTHER'));
-- Chốt chặn cuối: bán quá tồn kho thì UPDATE bị từ chối
ALTER TABLE venue_service ADD CONSTRAINT ck_service_stock CHECK (stock IS NULL OR stock >= 0);

UPDATE venue_service SET category = CASE
    WHEN name ILIKE '%nước%' THEN 'DRINK'
    WHEN name ILIKE '%áo%' OR name ILIKE '%giày%' THEN 'RENTAL'
    WHEN name ILIKE '%bóng%' THEN 'BALL'
    WHEN name ILIKE '%trọng tài%' THEN 'REFEREE'
    ELSE 'OTHER' END;

-- Đặt kèm online được chọn số lượng
ALTER TABLE booking_service ADD COLUMN quantity SMALLINT NOT NULL DEFAULT 1;
ALTER TABLE booking_service ADD CONSTRAINT ck_booking_service_qty CHECK (quantity BETWEEN 1 AND 99);

-- Đơn bán tại quầy (gắn ô sân đang đá hoặc khách lẻ)
CREATE TABLE service_order (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id    BIGINT        NOT NULL REFERENCES venue(id) ON DELETE CASCADE,
    booking_id  BIGINT        REFERENCES booking(id) ON DELETE SET NULL,
    created_by  BIGINT        NOT NULL REFERENCES app_user(id),
    -- CASH / QR: trả ngay; ADD_TO_BOOKING: cộng vào tiền sân, thu khi check-out
    pay_mode    VARCHAR(20)   NOT NULL,
    total       NUMERIC(12,2) NOT NULL,
    paid_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_order_pay_mode CHECK (pay_mode IN ('CASH', 'QR', 'ADD_TO_BOOKING')),
    CONSTRAINT ck_order_booking CHECK (pay_mode <> 'ADD_TO_BOOKING' OR booking_id IS NOT NULL),
    CONSTRAINT ck_order_total CHECK (total >= 0)
);
CREATE INDEX ix_service_order_venue ON service_order (venue_id, created_at DESC);
CREATE INDEX ix_service_order_booking ON service_order (booking_id) WHERE booking_id IS NOT NULL;

CREATE TABLE service_order_item (
    order_id   BIGINT        NOT NULL REFERENCES service_order(id) ON DELETE CASCADE,
    service_id BIGINT        NOT NULL REFERENCES venue_service(id),
    name       VARCHAR(120)  NOT NULL,
    category   VARCHAR(20)   NOT NULL,
    price      NUMERIC(12,2) NOT NULL,
    quantity   SMALLINT      NOT NULL,
    PRIMARY KEY (order_id, service_id),
    CONSTRAINT ck_order_item_qty CHECK (quantity BETWEEN 1 AND 99)
);

-- Check-out đơn: đã kiểm đồ cho thuê, đã thu đủ tiền
ALTER TABLE booking ADD COLUMN checked_out_at TIMESTAMPTZ;
ALTER TABLE booking ADD COLUMN rentals_missing VARCHAR(300);

