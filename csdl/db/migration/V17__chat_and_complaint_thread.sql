-- Mỗi trận (đơn đặt sân) có tối đa một nhóm chat: chủ trận + đội khách / người chơi lẻ đã được nhận
CREATE UNIQUE INDEX IF NOT EXISTS uq_conversation_booking ON conversation (booking_id) WHERE booking_id IS NOT NULL;

-- Đếm tin chưa đọc theo từng thành viên
ALTER TABLE conversation_member ADD COLUMN IF NOT EXISTS last_read_at TIMESTAMPTZ;
CREATE INDEX IF NOT EXISTS ix_conversation_member_user ON conversation_member (user_id);

-- Trao đổi giữa Admin và người gửi khiếu nại:
-- Admin "Yêu cầu bổ sung thông tin" (ticket -> NEED_INFO, hẹn 24h), người gửi trả lời (ticket -> IN_PROGRESS)
CREATE TABLE IF NOT EXISTS complaint_message (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT        NOT NULL REFERENCES complaint_ticket(id) ON DELETE CASCADE,
    author_id  BIGINT        NOT NULL REFERENCES app_user(id),
    content    VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_complaint_message_ticket ON complaint_message (ticket_id, created_at);
